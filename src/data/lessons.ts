export type StepKind = 'predict' | 'terminal';
export type StepRole = 'learn' | 'drill' | 'prove';

export interface Lesson {
  id: string;
  nodeId: string;
  arc: string;
  role: StepRole;
  kind: StepKind;
  index: number;
  type: 'command' | 'puzzle' | 'scenario';
  title: string;
  track: string;
  prompt: string;
  /** Why this matters. Shown before practice. \n\n separates paragraphs. */
  concept: string;
  /** Worked example, hidden behind a toggle (guess first). Terminal steps only. */
  example?: string;
  /** One-liner shown after success. */
  takeaway: string;
  /** Touch-friendly key chips. Terminal steps only. */
  chips?: string[];
  /** Predict steps only. */
  question?: string;
  choices?: string[];
  answer?: number;
  explain?: string;
  startingFS?: Record<string, unknown>;
  startingCwd?: string;
  expected?: {
    command?: string;
    commandAlt?: string[];
    output?: string;
    outputAlt?: string[];
    fsState?: Record<string, unknown>;
    /** Ordered commands (subsequence of session history) for chaining missions. */
    sequence?: string[];
    /** Absolute path → permission string, e.g. {'/home/user/x': '-rwxr-xr-x'}. */
    modeState?: Record<string, string>;
  };
  hints: string[];
  xp: number;
}

