const HOME = '/home/user';

function t(
  l: Omit<Lesson, 'kind' | 'role' | 'index' | 'type'> & { kind?: StepKind; role?: StepRole },
): Lesson {
  return {
    kind: 'terminal',
    role: 'drill',
    type: 'command',
    ...l,
  } as Lesson;
}

function p(
  l: Omit<Lesson, 'kind' | 'role' | 'index' | 'type' | 'expected'> & {
    question: string;
    choices: string[];
    answer: number;
    explain: string;
  },
): Lesson {
  return { kind: 'predict', role: 'learn', type: 'puzzle', ...l } as Lesson;
}

